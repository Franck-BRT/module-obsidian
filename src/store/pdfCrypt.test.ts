const bytes = (base64: string): Uint8Array => Uint8Array.from(atob(base64), (char) => char.charCodeAt(0))
const hex = (data: Uint8Array): string => [...data].map((byte) => byte.toString(16).padStart(2, '0')).join('')
const text = (value: string): Uint8Array => new TextEncoder().encode(value)

describe('the ciphers', () => {
  it('hashes with MD5 as the reference vectors say', () => {
    expect(hex(md5(text('')))).toBe('d41d8cd98f00b204e9800998ecf8427e')
    expect(hex(md5(text('abc')))).toBe('900150983cd24fb0d6963f7d28e17f72')
    expect(hex(md5(text('12345678901234567890123456789012345678901234567890123456789012345678901234567890')))).toBe(
      '57edf4a22be3c955ac49da2e2107b67a'
    )
  })

  it('enciphers with RC4 as the reference vectors say, and back', () => {
    expect(hex(rc4(text('Key'), text('Plaintext')))).toBe('bbf316e8d940af0ad3')
    expect(new TextDecoder().decode(rc4(text('Key'), rc4(text('Key'), text('Plaintext'))))).toBe('Plaintext')
  })
})

describe('readPdf, on a locked file', () => {
  for (const name of ['rc440', 'rc4128', 'aes128', 'aes256'] as const) {
    it(`reads one locked with ${name}, which opens with no password`, async () => {
      const content = await readPdf(bytes(LOCKED[name]))
      expect(content.items.map((item) => item.text)).toEqual(['Essais de type 1', 'Paragraphe 6.3.5'])
      expect(content.problems).toEqual([])
    })
  }

  it('refuses one that needs a password to open, saying so', async () => {
    await expect(readPdf(bytes(LOCKED.password))).rejects.toThrow(/encrypted: a password is needed/)
  })
})
